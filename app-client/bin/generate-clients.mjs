#!/usr/bin/env node
/**
 * CLI tool to generate app-to-app fetch clients
 * Part of @major-tech/app-client
 *
 * Usage:
 *   major-app-client add <app_id> <name> [description] [--framework <nextjs|vite>]
 *   major-app-client remove <name> [--framework <nextjs|vite>]
 *   major-app-client list
 */

import * as fs from 'fs';
import * as path from 'path';

const projectRoot = process.cwd();
const appsConfigPath = path.join(projectRoot, 'apps.json');

const RESOURCE_MARKER = 'Auto-generated by @major-tech/resource-client';
const AGENT_MARKER = 'Auto-generated by @major-tech/agents-client';
const APP_MARKER = 'Auto-generated by @major-tech/app-client';
const MARKERS = [RESOURCE_MARKER, AGENT_MARKER, APP_MARKER];

function getClientsDir() {
  const srcDir = path.join(projectRoot, 'src');

  if (fs.existsSync(srcDir)) {
    return path.join(srcDir, 'clients');
  }

  return path.join(projectRoot, 'clients');
}

function toCamelCase(str) {
  return str
    .toLowerCase()
    .replace(/[^a-z0-9]+(.)/g, (_, char) => char.toUpperCase())
    .replace(/[^a-z0-9]+$/, '')
    .replace(/^[^a-z]+/, '');
}

function collectGeneratedClientExports(clientsDir) {
  if (!fs.existsSync(clientsDir)) {
    return [];
  }

  const exports = [];

  for (const f of fs.readdirSync(clientsDir)) {
    if (!f.endsWith('.ts') || f === 'index.ts' || f === 'bindings.ts') {
      continue;
    }

    const p = path.join(clientsDir, f);

    if (!fs.statSync(p).isFile()) {
      continue;
    }

    const content = fs.readFileSync(p, 'utf-8');

    if (!MARKERS.some((m) => content.includes(m))) {
      continue;
    }

    const match = content.match(/export (?:const|function) (\w+)/);

    if (!match) {
      continue;
    }

    exports.push({ name: match[1], base: f.replace(/\.ts$/, '') });
  }

  exports.sort((a, b) => a.name.localeCompare(b.name));

  return exports.map((e) => `export { ${e.name} } from './${e.base}';`);
}

function writeMergedIndex(clientsDir) {
  const clientExports = collectGeneratedClientExports(clientsDir);
  const hasBindings = fs.existsSync(path.join(clientsDir, 'bindings.ts'));

  let body;

  if (hasBindings) {
    body = `// DO NOT EDIT - Auto-generated by @major-tech/resource-client
export { getResourceId, getAgentId, getApplicationId, type ResourceSlot, type AgentSlot } from './bindings';

${clientExports.join('\n')}
`;
  } else if (clientExports.length === 0) {
    body = `// No clients configured\n`;
  } else {
    body = `/**
 * Auto-generated client exports
 * DO NOT EDIT
 */

${clientExports.join('\n')}
`;
  }

  fs.writeFileSync(path.join(clientsDir, 'index.ts'), body, 'utf-8');
}

function deleteMarkedFiles(clientsDir) {
  if (!fs.existsSync(clientsDir)) {
    return;
  }

  for (const f of fs.readdirSync(clientsDir)) {
    const p = path.join(clientsDir, f);

    if (fs.statSync(p).isFile() && fs.readFileSync(p, 'utf-8').includes(APP_MARKER)) {
      fs.unlinkSync(p);
    }
  }
}

function clientTemplate(app, framework) {
  const isNextJs = framework !== 'vite';
  const env = isNextJs ? 'process.env' : 'import.meta.env';
  const serverOnly = isNextJs ? "import 'server-only';\n" : '';
  const entry = isNextJs ? '@major-tech/app-client/next' : '@major-tech/app-client';
  const name = toCamelCase(app.name) + 'Fetch';

  return `${serverOnly}import { createAppFetch } from '${entry}';

/**
 * ${app.description || app.name}
 * App ID: ${app.id}
 * DO NOT EDIT - ${APP_MARKER}
 */
export const ${name} = createAppFetch({
  baseUrl: ${env}.MAJOR_API_BASE_URL || 'https://go-api.prod.major.build',
  appId: '${app.id}',
  majorJwtToken: ${env}.MAJOR_JWT_TOKEN!,
});
`;
}

function loadApps() {
  if (!fs.existsSync(appsConfigPath)) {
    return [];
  }

  return JSON.parse(fs.readFileSync(appsConfigPath, 'utf-8'));
}

function saveApps(apps) {
  fs.writeFileSync(appsConfigPath, JSON.stringify(apps, null, 2), 'utf-8');
}

function regenerateClients(apps, framework) {
  const clientsDir = getClientsDir();

  if (!fs.existsSync(clientsDir)) {
    fs.mkdirSync(clientsDir, { recursive: true });
  }

  deleteMarkedFiles(clientsDir);

  for (const app of apps) {
    fs.writeFileSync(path.join(clientsDir, toCamelCase(app.name) + '.ts'), clientTemplate(app, framework), 'utf-8');
  }

  writeMergedIndex(clientsDir);

  console.log(`✅ Generated ${apps.length} app client(s) in ${clientsDir}`);
}

function addApp(appId, name, description, framework) {
  const apps = loadApps();

  if (apps.some((a) => a.name === name)) {
    console.error(`❌ App client with name "${name}" already exists`);
    process.exit(1);
  }

  const clientFile = path.join(getClientsDir(), toCamelCase(name) + '.ts');

  if (fs.existsSync(clientFile) && !fs.readFileSync(clientFile, 'utf-8').includes(APP_MARKER)) {
    console.error(`❌ ${clientFile} already exists and was not generated by @major-tech/app-client; pick another name`);
    process.exit(1);
  }

  apps.push({ id: appId, name, description: description || name });
  saveApps(apps);

  const fetchName = toCamelCase(name) + 'Fetch';

  console.log(`✅ Added app client: ${name}`);
  console.log(`   ID: ${appId}`);
  console.log(`   import { ${fetchName} } from './clients';`);

  regenerateClients(apps, framework);
}

function removeApp(name, framework) {
  const apps = loadApps();
  const index = apps.findIndex((a) => a.name === name);

  if (index === -1) {
    console.error(`❌ App client "${name}" not found`);
    process.exit(1);
  }

  const removed = apps.splice(index, 1)[0];
  saveApps(apps);

  console.log(`✅ Removed app client: ${removed.name}`);

  regenerateClients(apps, framework);
}

function listApps() {
  const apps = loadApps();

  if (apps.length === 0) {
    console.log('No app clients configured');
    return;
  }

  for (const a of apps) {
    console.log(`${a.name}  ${a.id}  ${toCamelCase(a.name)}Fetch`);
  }
}

function main() {
  const args = process.argv.slice(2);
  const frameworkIndex = args.indexOf('--framework');
  let framework = undefined;

  if (frameworkIndex !== -1 && args[frameworkIndex + 1]) {
    framework = args[frameworkIndex + 1];
    args.splice(frameworkIndex, 2);
  }

  const [command, a1, a2, a3] = args;

  switch (command) {
    case 'add': {
      if (!a1 || !a2) {
        console.error('❌ Usage: add <app_id> <name> [description] [--framework <nextjs|vite>]');
        process.exit(1);
      }

      addApp(a1, a2, a3, framework);
      break;
    }

    case 'remove': {
      if (!a1) {
        console.error('❌ Usage: remove <name> [--framework <nextjs|vite>]');
        process.exit(1);
      }

      removeApp(a1, framework);
      break;
    }

    case 'list': {
      listApps();
      break;
    }

    default: {
      console.log('Usage:');
      console.log('  major-app-client add <app_id> <name> [description] [--framework <nextjs|vite>]');
      console.log('  major-app-client remove <name> [--framework <nextjs|vite>]');
      console.log('  major-app-client list');
      process.exit(command ? 1 : 0);
    }
  }
}

main();
