#!/usr/bin/env node
/**
 * CLI tool to generate singleton agent clients
 * Part of @major-tech/agents-client
 *
 * Usage:
 *   npx @major-tech/agents-client add <agent_id> <name> [description]
 *   npx @major-tech/agents-client remove <name>
 *   npx @major-tech/agents-client list
 *   npx @major-tech/agents-client generate [--framework <nextjs|vite>]
 *
 * Examples:
 *   npx @major-tech/agents-client add "abc-123" "support-bot" "Handles support tickets"
 *   npx @major-tech/agents-client remove "support-bot"
 *   npx @major-tech/agents-client generate --framework nextjs
 */

import * as fs from 'fs';
import * as path from 'path';

const projectRoot = process.cwd();
const agentsConfigPath = path.join(projectRoot, 'agents.json');

const RESOURCE_MARKER = 'Auto-generated by @major-tech/resource-client';
const AGENT_MARKER = 'Auto-generated by @major-tech/agents-client';

function getClientsDir() {
  const srcDir = path.join(projectRoot, 'src');

  if (fs.existsSync(srcDir)) {
    return path.join(srcDir, 'clients');
  }

  return path.join(projectRoot, 'clients');
}

function toCamelCase(str) {
  return str
    .toLowerCase()
    .replace(/[^a-z0-9]+(.)/g, (_, char) => char.toUpperCase())
    .replace(/[^a-z0-9]+$/, '')
    .replace(/^[^a-z]+/, '');
}

const slotClientName = (slot) => toCamelCase(slot.toLowerCase()) + 'Client';
const slotFileBase = (slot) => toCamelCase(slot.toLowerCase()) || 'agent';

function envReads(framework) {
  const isNextJs = framework === 'nextjs';
  const root = isNextJs ? 'process.env' : 'import.meta.env';

  return { base: `${root}.MAJOR_API_BASE_URL`, jwt: `${root}.MAJOR_JWT_TOKEN`, isNextJs };
}

function collectGeneratedClientExports(clientsDir) {
  if (!fs.existsSync(clientsDir)) {
    return [];
  }

  const exports = [];

  for (const f of fs.readdirSync(clientsDir)) {
    if (!f.endsWith('.ts') || f === 'index.ts' || f === 'bindings.ts') {
      continue;
    }

    const p = path.join(clientsDir, f);

    if (!fs.statSync(p).isFile()) {
      continue;
    }

    const content = fs.readFileSync(p, 'utf-8');

    if (!content.includes(RESOURCE_MARKER) && !content.includes(AGENT_MARKER)) {
      continue;
    }

    const match = content.match(/export (?:const|function) (\w+)/);

    if (!match) {
      continue;
    }

    exports.push({ name: match[1], base: f.replace(/\.ts$/, '') });
  }

  exports.sort((a, b) => a.name.localeCompare(b.name));

  return exports.map((e) => `export { ${e.name} } from './${e.base}';`);
}

function writeMergedIndex(clientsDir) {
  const clientExports = collectGeneratedClientExports(clientsDir);
  const hasBindings = fs.existsSync(path.join(clientsDir, 'bindings.ts'));

  let body;

  if (hasBindings) {
    body = `// DO NOT EDIT - Auto-generated by @major-tech/resource-client
export { getResourceId, getAgentId, getApplicationId, type ResourceSlot, type AgentSlot } from './bindings';

${clientExports.join('\n')}
`;
  } else if (clientExports.length === 0) {
    body = `// No clients configured\n`;
  } else {
    body = `/**
 * Auto-generated client exports
 * DO NOT EDIT
 */

${clientExports.join('\n')}
`;
  }

  fs.writeFileSync(path.join(clientsDir, 'index.ts'), body, 'utf-8');
}

function deleteMarkedFiles(clientsDir, marker) {
  if (!fs.existsSync(clientsDir)) {
    return;
  }

  for (const f of fs.readdirSync(clientsDir)) {
    if (f === 'bindings.ts') {
      continue;
    }

    const p = path.join(clientsDir, f);

    if (fs.statSync(p).isFile() && fs.readFileSync(p, 'utf-8').includes(marker)) {
      fs.unlinkSync(p);
    }
  }
}

function importLine(clientName) {
  return `import { ${clientName} } from './clients';`;
}

/**
 * Client template for legacy app mode — bakes the agent id into a singleton.
 */
function clientTemplateApp(data, framework) {
  const isNextJs = framework === 'nextjs';
  const headerImport = isNextJs ? `\nimport { headers } from 'next/headers';` : '';
  const getHeadersConfig = isNextJs
    ? `
        getHeaders: async () => {
          const h = await headers();
          return {
            'x-major-user-jwt': h.get('x-major-user-jwt') || '',
          };
        },`
    : '';
  const serverOnly = isNextJs ? "import 'server-only';\n" : '';

  return `${serverOnly}import { AgentsClient } from '@major-tech/agents-client';${headerImport}

/**
 * ${data.description}
 *
 * Agent ID: ${data.agentId}
 *
 * DO NOT EDIT - Auto-generated by @major-tech/agents-client
 */

const BASE_URL = ${isNextJs ? 'process.env.MAJOR_API_BASE_URL' : 'import.meta.env.MAJOR_API_BASE_URL'} || 'https://go-api.prod.major.build';
const MAJOR_JWT_TOKEN = ${isNextJs ? 'process.env.MAJOR_JWT_TOKEN' : 'import.meta.env.MAJOR_JWT_TOKEN'};

class ${data.clientName}Singleton {
  private static instance: AgentsClient | null = null;

  static getInstance(): AgentsClient {
    if (!${data.clientName}Singleton.instance) {
      ${data.clientName}Singleton.instance = new AgentsClient({
        baseUrl: BASE_URL,
        majorJwtToken: MAJOR_JWT_TOKEN,
        agentId: '${data.agentId}',
        fetch: (...args) => fetch(...args),${getHeadersConfig}
      });
    }
    return ${data.clientName}Singleton.instance;
  }
}

export const ${data.clientName} = ${data.clientName}Singleton.getInstance();
`;
}

function slotClientTemplate(slot, framework) {
  const { base, jwt, isNextJs } = envReads(framework);
  const headerImport = isNextJs ? `\nimport { headers } from 'next/headers';` : '';
  const getHeaders = isNextJs
    ? `
  getHeaders: async () => {
    const h = await headers();
    return { 'x-major-user-jwt': h.get('x-major-user-jwt') || '' };
  },`
    : '';
  const serverOnly = isNextJs ? "import 'server-only';\n" : '';

  return `${serverOnly}import { getAgentId } from './bindings';
import { AgentsClient } from '@major-tech/agents-client';${headerImport}

/**
 * Agent slot: ${slot}
 * DO NOT EDIT - Auto-generated by @major-tech/agents-client
 */
const BASE_URL = ${base} || 'https://go-api.prod.major.build';
const MAJOR_JWT_TOKEN = ${jwt};

export const ${slotClientName(slot)} = new AgentsClient({
  baseUrl: BASE_URL,
  majorJwtToken: MAJOR_JWT_TOKEN,
  agentId: getAgentId('${slot}'),
  fetch: (...args) => fetch(...args),${getHeaders}
});
`;
}

function loadAgents() {
  if (!fs.existsSync(agentsConfigPath)) {
    return [];
  }

  return JSON.parse(fs.readFileSync(agentsConfigPath, 'utf-8'));
}

function saveAgents(agents) {
  const dir = path.dirname(agentsConfigPath);

  if (!fs.existsSync(dir)) {
    fs.mkdirSync(dir, { recursive: true });
  }

  fs.writeFileSync(agentsConfigPath, JSON.stringify(agents, null, 2), 'utf-8');
}

function generateClientFile(agent, framework) {
  const clientName = toCamelCase(agent.name) + 'Client';

  return clientTemplateApp(
    {
      description: agent.description || agent.name,
      agentId: agent.id,
      clientName,
    },
    framework,
  );
}

function addAgent(agentId, name, description, framework) {
  const agents = loadAgents();
  const existing = agents.find((a) => a.name === name);

  if (existing) {
    console.error(`❌ Agent with name "${name}" already exists`);
    process.exit(1);
  }

  agents.push({
    id: agentId,
    name,
    description: description || name,
  });
  saveAgents(agents);

  const clientName = toCamelCase(name) + 'Client';

  console.log(`✅ Added agent: ${name}`);
  console.log(`   ID: ${agentId}`);
  console.log(`   ${importLine(clientName)}`);

  regenerateClients(agents, framework);
}

function removeAgent(name, framework) {
  const agents = loadAgents();
  const index = agents.findIndex((a) => a.name === name);

  if (index === -1) {
    console.error(`❌ Agent "${name}" not found`);
    process.exit(1);
  }

  const removed = agents.splice(index, 1)[0];
  saveAgents(agents);

  console.log(`✅ Removed agent: ${removed.name}`);
  console.log(`   ID: ${removed.id}`);

  regenerateClients(agents, framework);
}

function listAgents() {
  const agents = loadAgents();

  if (agents.length === 0) {
    console.log('No agents configured');
    return;
  }

  console.log(`Agents (${agents.length}):\n`);
  agents.forEach((a, idx) => {
    console.log(`${idx + 1}. ${a.name}`);
    console.log(`   ID: ${a.id}`);
    console.log(`   Client: ${toCamelCase(a.name)}Client`);
    console.log('');
  });
}

function regenerateClients(agents, framework) {
  const clientsDir = getClientsDir();

  if (!fs.existsSync(clientsDir)) {
    fs.mkdirSync(clientsDir, { recursive: true });
  }

  deleteMarkedFiles(clientsDir, AGENT_MARKER);

  agents.forEach((agent) => {
    const fileName = toCamelCase(agent.name) + '.ts';
    fs.writeFileSync(path.join(clientsDir, fileName), generateClientFile(agent, framework), 'utf-8');
  });

  writeMergedIndex(clientsDir);

  console.log(`✅ Generated ${agents.length} agent client(s) in ${clientsDir}`);

  if (framework) {
    console.log(`   Framework: ${framework}`);
  }
}

function loadBindings() {
  const p = path.join(projectRoot, 'bindings.json');

  if (!fs.existsSync(p)) {
    console.error('❌ bindings.json not found in project root.');
    process.exit(1);
  }

  return JSON.parse(fs.readFileSync(p, 'utf-8'));
}

function generateFromBindings(framework) {
  const bindings = loadBindings();
  const agents = bindings?.slots?.agents ?? {};
  const clientsDir = getClientsDir();

  if (!fs.existsSync(clientsDir)) {
    fs.mkdirSync(clientsDir, { recursive: true });
  }

  if (!fs.existsSync(path.join(clientsDir, 'bindings.ts'))) {
    console.error('❌ clients/bindings.ts not found. Run `major-client generate` first.');
    process.exit(1);
  }

  deleteMarkedFiles(clientsDir, AGENT_MARKER);

  for (const slot of Object.keys(agents)) {
    fs.writeFileSync(path.join(clientsDir, slotFileBase(slot) + '.ts'), slotClientTemplate(slot, framework), 'utf-8');
  }

  writeMergedIndex(clientsDir);

  const names = Object.keys(agents).map((slot) => slotClientName(slot));

  console.log(`✅ Generated ${names.length} agent client(s) + typed readers in ${clientsDir}`);

  for (const name of names) {
    console.log(`   ${importLine(name)}`);
  }
}

function main() {
  const args = process.argv.slice(2);
  const command = args[0];

  const frameworkIndex = args.indexOf('--framework');
  let framework = undefined;

  if (frameworkIndex !== -1 && args[frameworkIndex + 1]) {
    framework = args[frameworkIndex + 1];
    args.splice(frameworkIndex, 2);
  }

  if (!command) {
    console.log('Usage:');
    console.log('  npx @major-tech/agents-client add <agent_id> <name> [description] [--framework <nextjs|vite>]');
    console.log('  npx @major-tech/agents-client remove <name> [--framework <nextjs|vite>]');
    console.log('  npx @major-tech/agents-client list');
    console.log('  npx @major-tech/agents-client generate [--framework <nextjs|vite>]');
    return;
  }

  switch (command) {
    case 'add': {
      const [, agentId, name, description] = args;

      if (!agentId || !name) {
        console.error('❌ Missing arguments');
        console.log('Usage: add <agent_id> <name> [description] [--framework <nextjs|vite>]');
        process.exit(1);
      }

      addAgent(agentId, name, description, framework);
      break;
    }

    case 'remove': {
      const [, name] = args;

      if (!name) {
        console.error('❌ Missing name');
        process.exit(1);
      }

      removeAgent(name, framework);
      break;
    }

    case 'list': {
      listAgents();
      break;
    }

    case 'generate': {
      generateFromBindings(framework);
      break;
    }

    default: {
      console.error(`❌ Unknown command: ${command}`);
      process.exit(1);
    }
  }
}

main();
