#!/usr/bin/env node
/**
 * CLI tool to generate singleton workflow clients
 * Part of @major-tech/workflows-client
 *
 * Usage:
 *   npx @major-tech/workflows-client add <workflow_id> <name> [description] --framework <nextjs|hono>
 *   npx @major-tech/workflows-client remove <name> --framework <nextjs|hono>
 *   npx @major-tech/workflows-client list
 *
 * Each workflow is recorded in `workflows.json` and gets a generated client in
 * `src/clients/` (or `clients/`) with its id baked in. Deploy grants the app
 * permission to start exactly the workflows its generated clients name.
 */

import * as fs from 'fs';
import * as path from 'path';

const projectRoot = process.cwd();
const workflowsConfigPath = path.join(projectRoot, 'workflows.json');

const RESOURCE_MARKER = 'Auto-generated by @major-tech/resource-client';
const AGENT_MARKER = 'Auto-generated by @major-tech/agents-client';
const WORKFLOW_MARKER = 'Auto-generated by @major-tech/workflows-client';

function getClientsDir() {
  const srcDir = path.join(projectRoot, 'src');

  if (fs.existsSync(srcDir)) {
    return path.join(srcDir, 'clients');
  }

  return path.join(projectRoot, 'clients');
}

function toCamelCase(str) {
  return str
    .toLowerCase()
    .replace(/[^a-z0-9]+(.)/g, (_, char) => char.toUpperCase())
    .replace(/[^a-z0-9]+$/, '')
    .replace(/^[^a-z]+/, '');
}

const clientName = (name) => toCamelCase(name) + 'WorkflowClient';
const fileBase = (name) => toCamelCase(name) + 'Workflow';

// The clients index is shared with the resource and agents generators: keep
// every generated client, whichever package wrote it.
function collectGeneratedClientExports(clientsDir) {
  if (!fs.existsSync(clientsDir)) {
    return [];
  }

  const exports = [];

  for (const f of fs.readdirSync(clientsDir)) {
    if (!f.endsWith('.ts') || f === 'index.ts' || f === 'bindings.ts') {
      continue;
    }

    const p = path.join(clientsDir, f);

    if (!fs.statSync(p).isFile()) {
      continue;
    }

    const content = fs.readFileSync(p, 'utf-8');

    if (!content.includes(RESOURCE_MARKER) && !content.includes(AGENT_MARKER) && !content.includes(WORKFLOW_MARKER)) {
      continue;
    }

    const match = content.match(/export (?:const|function) (\w+)/);

    if (!match) {
      continue;
    }

    exports.push({ name: match[1], base: f.replace(/\.ts$/, '') });
  }

  exports.sort((a, b) => a.name.localeCompare(b.name));

  return exports.map((e) => `export { ${e.name} } from './${e.base}';`);
}

function writeMergedIndex(clientsDir) {
  const clientExports = collectGeneratedClientExports(clientsDir);
  const hasBindings = fs.existsSync(path.join(clientsDir, 'bindings.ts'));

  let body;

  if (hasBindings) {
    body = `// DO NOT EDIT - Auto-generated by @major-tech/resource-client
export { getResourceId, getAgentId, getApplicationId, type ResourceSlot, type AgentSlot } from './bindings';

${clientExports.join('\n')}
`;
  } else if (clientExports.length === 0) {
    body = `// No clients configured\n`;
  } else {
    body = `/**
 * Auto-generated client exports
 * DO NOT EDIT
 */

${clientExports.join('\n')}
`;
  }

  fs.writeFileSync(path.join(clientsDir, 'index.ts'), body, 'utf-8');
}

function deleteMarkedFiles(clientsDir) {
  if (!fs.existsSync(clientsDir)) {
    return;
  }

  for (const f of fs.readdirSync(clientsDir)) {
    const p = path.join(clientsDir, f);

    if (fs.statSync(p).isFile() && fs.readFileSync(p, 'utf-8').includes(WORKFLOW_MARKER)) {
      fs.unlinkSync(p);
    }
  }
}

function clientTemplate(workflow, framework) {
  const isNextJs = framework === 'nextjs';
  const isHono = framework === 'hono';
  const entry = isNextJs ? '@major-tech/workflows-client/next' : '@major-tech/workflows-client';
  const serverOnly = isNextJs ? "import 'server-only';\n" : '';
  const headerImport = isHono ? "\nimport { tryGetContext } from 'hono/context-storage';" : '';
  const getHeadersConfig = isHono ? `
  getHeaders: (): Record<string, string> => {
    const userJwt = tryGetContext()?.req.header('x-major-user-jwt');
    return userJwt ? { 'x-major-user-jwt': userJwt } : {};
  },` : '';

  return `${serverOnly}import { createWorkflowsClient } from '${entry}';${headerImport}

/**
 * ${workflow.description || workflow.name}
 *
 * Workflow ID: ${workflow.id}
 *
 * DO NOT EDIT - ${WORKFLOW_MARKER}
 */
export const ${clientName(workflow.name)} = createWorkflowsClient({
  baseUrl: process.env.MAJOR_API_BASE_URL || 'https://go-api.prod.major.build',
  majorJwtToken: process.env.MAJOR_JWT_TOKEN,
  workflowId: '${workflow.id}',
  fetch: (...args) => fetch(...args),${getHeadersConfig}
});
`;
}

function loadWorkflows() {
  if (!fs.existsSync(workflowsConfigPath)) {
    return [];
  }

  return JSON.parse(fs.readFileSync(workflowsConfigPath, 'utf-8'));
}

function saveWorkflows(workflows) {
  fs.writeFileSync(workflowsConfigPath, JSON.stringify(workflows, null, 2) + '\n', 'utf-8');
}

function regenerateClients(workflows, framework) {
  const clientsDir = getClientsDir();

  if (!fs.existsSync(clientsDir)) {
    fs.mkdirSync(clientsDir, { recursive: true });
  }

  deleteMarkedFiles(clientsDir);

  for (const workflow of workflows) {
    fs.writeFileSync(path.join(clientsDir, fileBase(workflow.name) + '.ts'), clientTemplate(workflow, framework), 'utf-8');
  }

  writeMergedIndex(clientsDir);

  console.log(`✅ Generated ${workflows.length} workflow client(s) in ${clientsDir}`);
}

function addWorkflow(workflowId, name, description, framework) {
  const workflows = loadWorkflows();

  if (workflows.some((w) => w.name === name)) {
    console.error(`❌ Workflow with name "${name}" already exists`);
    process.exit(1);
  }

  workflows.push({ id: workflowId, name, description: description || name });
  saveWorkflows(workflows);

  console.log(`✅ Added workflow: ${name}`);
  console.log(`   ID: ${workflowId}`);
  console.log(`   import { ${clientName(name)} } from './clients';`);

  regenerateClients(workflows, framework);
}

function removeWorkflow(name, framework) {
  const workflows = loadWorkflows();
  const index = workflows.findIndex((w) => w.name === name);

  if (index === -1) {
    console.error(`❌ Workflow "${name}" not found`);
    process.exit(1);
  }

  const [removed] = workflows.splice(index, 1);
  saveWorkflows(workflows);

  console.log(`✅ Removed workflow: ${removed.name}`);

  regenerateClients(workflows, framework);
}

function listWorkflows() {
  const workflows = loadWorkflows();

  if (workflows.length === 0) {
    console.log('No workflows configured');
    return;
  }

  console.log(`Workflows (${workflows.length}):\n`);
  for (const w of workflows) {
    console.log(`- ${w.name}`);
    console.log(`  ID: ${w.id}`);
    console.log(`  Client: ${clientName(w.name)}`);
  }
}

function main() {
  const args = process.argv.slice(2);
  const frameworkIndex = args.indexOf('--framework');
  let framework;

  if (frameworkIndex !== -1 && args[frameworkIndex + 1]) {
    framework = args[frameworkIndex + 1];
    args.splice(frameworkIndex, 2);
  }

  const [command, ...rest] = args;

  if ((command === 'add' || command === 'remove') && framework !== 'nextjs' && framework !== 'hono') {
    console.error('Workflow clients run on the server. Pass --framework nextjs or --framework hono. For Vite apps, run this command in the Hono backend with --framework hono.');
    process.exit(1);
  }

  switch (command) {
    case 'add': {
      const [workflowId, name, description] = rest;

      if (!workflowId || !name) {
        console.error('Usage: add <workflow_id> <name> [description] --framework <nextjs|hono>');
        process.exit(1);
      }

      addWorkflow(workflowId, name, description, framework);
      break;
    }

    case 'remove': {
      const [name] = rest;

      if (!name) {
        console.error('Usage: remove <name> --framework <nextjs|hono>');
        process.exit(1);
      }

      removeWorkflow(name, framework);
      break;
    }

    case 'list': {
      listWorkflows();
      break;
    }

    default: {
      console.log('Usage:');
      console.log('  npx @major-tech/workflows-client add <workflow_id> <name> [description] --framework <nextjs|hono>');
      console.log('  npx @major-tech/workflows-client remove <name> --framework <nextjs|hono>');
      console.log('  npx @major-tech/workflows-client list');
      process.exit(command ? 1 : 0);
    }
  }
}

main();
